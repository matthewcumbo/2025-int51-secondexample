// Variables are like boxes that can hold data
// cannot be named a keyword
// should be meaningful
// cannot start with a number
// avoid special characters
// names must be unique

// String Variable (i.e. text)
let firstName = "Matthew";
console.log(firstName);

// Integer/Number Variable
let age = 34;
console.log(age);

// Boolean Variable (i.e. true/false)
let sleepy = true;
console.log(sleepy);

// JS is a dynamic language
// i.e. Variable data types can change during runtime
console.log(typeof(firstName));
firstName = 1;
console.log(typeof(firstName));

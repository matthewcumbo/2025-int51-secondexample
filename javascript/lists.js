// Arrays are lists of objects/variables 

// Empty Array
let list = [];
console.log(list);

// Replacing the values of an array
list = ["Joe","Doris","Ganni","Concetta"];
console.log(list);

// We can create a list immediately having values
let colors = ["red", "green", "blue"];
console.log(colors);

// Accessing a value in an Array based on it position
// P.S. Array positions always start at 0
console.log(colors[1]);

// We can also check how many values an array has
console.log(colors.length);